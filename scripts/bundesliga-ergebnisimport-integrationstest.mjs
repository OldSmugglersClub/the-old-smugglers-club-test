import fs from "node:fs";
const SOURCE="spieldaten.json", TEMP="spieldaten.integration-test.json";
const clone=v=>JSON.parse(JSON.stringify(v));
const games=d=>(Array.isArray(d?.saisons)?d.saisons:[]).flatMap(s=>Array.isArray(s?.spiele)?s.spiele:[]).filter(m=>m?.wettbewerb==="bundesliga"&&m?.saison==="2026/2027");
const has=m=>Number.isInteger(m?.heimtore)&&Number.isInteger(m?.auswaertstore);
const ok=(c,m)=>{if(!c)throw new Error("INTEGRATIONSTEST FEHLGESCHLAGEN: "+m);};
if(!fs.existsSync(SOURCE))throw new Error("spieldaten.json fehlt.");
const originalText=fs.readFileSync(SOURCE,"utf8");
const original=JSON.parse(originalText), work=clone(original), list=games(work);
ok(list.length===306,`306 Bundesliga-Spiele erwartet, gefunden: ${list.length}`);
const target=list.find(m=>!has(m)); ok(target,"Kein ergebnisloses Bundesliga-Spiel gefunden.");
const version=Number(work.datenVersion||0), before=clone(list);
target.heimtore=2; target.auswaertstore=1; target.status="beendet"; target.quelleStand="2099-01-01";
work.aktualisiert="2099-01-01"; work.datenVersion=version+1;
const after=games(work), changed=[];
for(let i=0;i<before.length;i++) if(JSON.stringify(before[i])!==JSON.stringify(after[i])) changed.push(after[i].id);
ok(changed.length===1,`Genau 1 Spiel muss geändert sein, tatsächlich: ${changed.length}`);
ok(changed[0]===target.id,"Falsches Spiel geändert.");
ok(target.heimtore===2&&target.auswaertstore===1,"Testergebnis fehlt.");
ok(target.status==="beendet","Status nicht beendet.");
ok(target.quelleStand==="2099-01-01","quelleStand falsch.");
ok(work.datenVersion===version+1,"datenVersion nicht exakt +1.");
fs.writeFileSync(TEMP,JSON.stringify(work,null,2)+"\n","utf8");
const conflictLocal=clone(target), incoming={home:3,away:1};
const conflict=has(conflictLocal)&&(conflictLocal.heimtore!==incoming.home||conflictLocal.auswaertstore!==incoming.away);
ok(conflict,"Abweichendes Ergebnis nicht als Konflikt erkannt.");
const beforeConflict=JSON.stringify(conflictLocal);
if(!conflict){conflictLocal.heimtore=incoming.home;conflictLocal.auswaertstore=incoming.away;}
ok(JSON.stringify(conflictLocal)===beforeConflict,"Konflikt hat Ergebnis verändert.");
ok(fs.readFileSync(SOURCE,"utf8")===originalText,"ECHTE spieldaten.json wurde verändert.");
console.log(`INTEGRATIONSTEST 1 BESTANDEN: ${target.id} temporär 2:1, genau ein Spiel geändert.`);
console.log("INTEGRATIONSTEST 2 BESTANDEN: Abweichendes bestehendes Ergebnis wird nicht überschrieben.");
console.log(`datenVersion-Test BESTANDEN: ${version} -> ${version+1}.`);
console.log("SCHUTZ BESTANDEN: echte spieldaten.json blieb bytegenau unverändert.");
